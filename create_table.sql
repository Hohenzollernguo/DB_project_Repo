

create table public.district
(
    district_id smallint generated by default as identity primary key,
    name_en     text not null unique check (btrim(name_en) <> '')
);

create table public.station
(
    station_id   bigint generated by default as identity primary key,
    chinese_name text     not null check (btrim(chinese_name) <> ''),
    english_name text     not null check (btrim(english_name) <> ''),
    district_id  smallint not null references public.district (district_id)
        on delete restrict on update restrict,
    unique (chinese_name, district_id)
);

create index idx_station_english_name on public.station (english_name);
create index idx_station_district_id on public.station (district_id);

create table public.metro_line
(
    line_id      bigint generated by default as identity primary key,
    chinese_name text not null unique check (btrim(chinese_name) <> ''),
    english_name text not null unique check (btrim(english_name) <> '')
);

create table public.line_station
(
    line_id          bigint   not null references public.metro_line (line_id)
        on delete restrict on update restrict,
    station_id       bigint   not null references public.station (station_id)
        on delete restrict on update restrict,
    position         integer  not null check (position > 0),
    status           text     not null check (status in ('Operation', 'Construction')),
    opening_year     smallint not null check (opening_year > 0),
    start_time       time without time zone,
    end_time         time without time zone,
    source_latitude  numeric(9, 6),
    source_longitude numeric(9, 6),
    primary key (line_id, station_id),
    constraint uq_line_position
        unique (line_id, position) deferrable initially deferred
);


create index idx_line_station_station_id on public.line_station (station_id);

create table public.station_exit
(
    exit_id     bigint generated by default as identity primary key,
    station_id  bigint not null references public.station (station_id)
        on delete restrict on update restrict,
    exit_code   text not null check (btrim(exit_code) <> ''),
    unique (station_id, exit_code)
);

create table public.landmark
(
    landmark_id bigint generated by default as identity primary key,
    name        text not null unique check (btrim(name) <> '')
);

create table public.exit_landmark
(
    exit_id     bigint not null references public.station_exit (exit_id)
        on delete restrict on update restrict,
    landmark_id bigint not null references public.landmark (landmark_id)
        on delete restrict on update restrict,
    primary key (exit_id, landmark_id)
);

create index idx_exit_landmark_landmark_id
    on public.exit_landmark (landmark_id);

create index idx_landmark_name_prefix
    on public.landmark (name text_pattern_ops);
